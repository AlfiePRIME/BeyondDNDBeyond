#!/usr/bin/env node
// Generates the built-in preset avatars (Prompt 13): low-poly blocky
// mannequins built from primitive geometry, exported as .glb into
// public/avatars/presets/, plus the TS manifest the picker renders from.
// Re-run after changing PRESETS; commit the regenerated output.
//
// Usage: node scripts/assets/generate-avatar-presets.mjs

import { mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as THREE from "three";
import { GLTFExporter } from "three/examples/jsm/exporters/GLTFExporter.js";

// GLTFExporter's binary path reads Blobs via FileReader, which Node doesn't
// provide — a minimal arrayBuffer-only shim is enough for geometry+material
// exports (no textures/canvas anywhere in these presets, by design).
if (typeof globalThis.FileReader === "undefined") {
  globalThis.FileReader = class FileReader {
    readAsArrayBuffer(blob) {
      blob.arrayBuffer().then((result) => {
        this.result = result;
        this.onloadend?.();
      });
    }
  };
}

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(rootDir, "public", "avatars", "presets");
const manifestPath = join(rootDir, "src", "app", "account", "avatar-presets.ts");

const PRESETS = [
  { id: "vanguard", label: "Vanguard", color: 0xc0392b, head: "box", build: "broad" },
  { id: "mystic", label: "Mystic", color: 0x8e44ad, head: "cone", build: "slim" },
  { id: "warden", label: "Warden", color: 0x27ae60, head: "cylinder", build: "regular" },
  { id: "corsair", label: "Corsair", color: 0x2980b9, head: "sphere", build: "slim" },
  { id: "ember", label: "Ember", color: 0xd35400, head: "sphere", build: "broad" },
];

function buildMannequin({ color, head, build }) {
  const group = new THREE.Group();
  const material = new THREE.MeshStandardMaterial({ color });
  const skin = new THREE.MeshStandardMaterial({
    color: new THREE.Color(color).lerp(new THREE.Color(0xffffff), 0.35),
  });

  const torsoWidth = build === "broad" ? 0.55 : build === "slim" ? 0.38 : 0.46;
  const add = (geometry, mat, x, y, z) => {
    const mesh = new THREE.Mesh(geometry, mat);
    mesh.position.set(x, y, z);
    group.add(mesh);
  };

  add(new THREE.BoxGeometry(torsoWidth, 0.6, 0.26), material, 0, 1.05, 0);
  add(new THREE.BoxGeometry(0.14, 0.7, 0.16), material, -torsoWidth / 4, 0.4, 0);
  add(new THREE.BoxGeometry(0.14, 0.7, 0.16), material, torsoWidth / 4, 0.4, 0);
  add(new THREE.BoxGeometry(0.11, 0.55, 0.13), skin, -(torsoWidth / 2 + 0.09), 1.05, 0);
  add(new THREE.BoxGeometry(0.11, 0.55, 0.13), skin, torsoWidth / 2 + 0.09, 1.05, 0);

  const headGeometry =
    head === "box"
      ? new THREE.BoxGeometry(0.28, 0.28, 0.28)
      : head === "cone"
        ? new THREE.ConeGeometry(0.18, 0.36, 8)
        : head === "cylinder"
          ? new THREE.CylinderGeometry(0.15, 0.15, 0.28, 10)
          : new THREE.SphereGeometry(0.17, 10, 8);
  add(headGeometry, skin, 0, 1.55, 0);

  return group;
}

function exportGlb(scene) {
  return new Promise((resolve, reject) => {
    new GLTFExporter().parse(
      scene,
      (result) => resolve(Buffer.from(result)),
      reject,
      { binary: true }
    );
  });
}

mkdirSync(outDir, { recursive: true });

for (const preset of PRESETS) {
  const scene = new THREE.Scene();
  scene.add(buildMannequin(preset));
  const glb = await exportGlb(scene);
  const magic = glb.toString("ascii", 0, 4);
  if (magic !== "glTF") throw new Error(`export of ${preset.id} produced invalid GLB (magic: ${magic})`);
  writeFileSync(join(outDir, `${preset.id}.glb`), glb);
  console.log(`wrote public/avatars/presets/${preset.id}.glb (${glb.length} bytes)`);
}

const manifest = `// Generated by scripts/assets/generate-avatar-presets.mjs — do not edit by hand.

export interface AvatarPreset {
  id: string;
  label: string;
  file: string;
}

export const AVATAR_PRESETS: readonly AvatarPreset[] = [
${PRESETS.map((p) => `  { id: "${p.id}", label: "${p.label}", file: "/avatars/presets/${p.id}.glb" },`).join("\n")}
] as const;
`;
writeFileSync(manifestPath, manifest);
console.log(`wrote src/app/account/avatar-presets.ts (${PRESETS.length} presets)`);
