#!/usr/bin/env node
// Generates src/ui-components/m3-tokens.css — the Material 3 dark color
// scheme (and a few harmonized custom colors) from the app's seed color.
// Re-run after changing SEED/TERTIARY_SEED; the output is committed so the
// app has no runtime dependency on the color library.
//
// Usage: node scripts/design/generate-m3-tokens.mjs
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  Blend,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

const SEED = "#9b00ff"; // the app's original purple
const TERTIARY_SEED = "#ff2d78"; // the original pink, kept as tertiary
// Semantic colors the table relies on (party/success teal, warning orange),
// harmonized toward the seed so they sit in the same scheme.
const CUSTOM = { teal: "#1ec8c8", orange: "#ff9a3c" };

const seedArgb = argbFromHex(SEED);
const base = new SchemeTonalSpot(Hct.fromInt(seedArgb), true, 0);
const pink = Hct.fromInt(argbFromHex(TERTIARY_SEED));
const scheme = new DynamicScheme({
  sourceColorArgb: seedArgb,
  variant: base.variant,
  contrastLevel: 0,
  isDark: true,
  primaryPalette: base.primaryPalette,
  secondaryPalette: base.secondaryPalette,
  tertiaryPalette: TonalPalette.fromHueAndChroma(pink.hue, 48),
  neutralPalette: base.neutralPalette,
  neutralVariantPalette: base.neutralVariantPalette,
});

const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "background", "onBackground",
  "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
  "surfaceDim", "surfaceBright",
  "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "outline", "outlineVariant", "shadow", "scrim",
  "inverseSurface", "inverseOnSurface", "inversePrimary",
];
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const lines = [];
for (const role of ROLES) {
  const color = MaterialDynamicColors[role];
  lines.push(`  --md-sys-color-${kebab(role)}: ${hexFromArgb(color.getArgb(scheme))};`);
}
for (const [name, hex] of Object.entries(CUSTOM)) {
  const harmonized = Blend.harmonize(argbFromHex(hex), seedArgb);
  const palette = TonalPalette.fromInt(harmonized);
  // M3 custom-color roles for a dark scheme: color 80 / on 20 / container 30 / on-container 90.
  lines.push(`  --md-custom-color-${name}: ${hexFromArgb(palette.tone(80))};`);
  lines.push(`  --md-custom-color-on-${name}: ${hexFromArgb(palette.tone(20))};`);
  lines.push(`  --md-custom-color-${name}-container: ${hexFromArgb(palette.tone(30))};`);
  lines.push(`  --md-custom-color-on-${name}-container: ${hexFromArgb(palette.tone(90))};`);
}

const out = `/*
 * Material 3 color scheme — GENERATED by scripts/design/generate-m3-tokens.mjs
 * (seed ${SEED}, tertiary ${TERTIARY_SEED}, dark). Do not edit by hand;
 * change the seeds in the script and re-run it.
 */

:root {
  color-scheme: dark;
${lines.join("\n")}
}
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "ui-components", "m3-tokens.css");
writeFileSync(target, out);
console.log(`wrote ${target}`);
